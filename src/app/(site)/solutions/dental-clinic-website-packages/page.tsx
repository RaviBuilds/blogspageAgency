import type { Metadata } from "next";
import { notFound } from "next/navigation";

import { DentalPackagesLanding } from "@/components/solutions/dental-packages-landing";
import { DENTAL_PACKAGES_HEADINGS } from "@/components/solutions/dental-packages-headings";
import { Breadcrumb } from "@/components/seo/breadcrumb";
import { JsonLd } from "@/components/seo/json-ld";
import { findApprovedCity } from "@/lib/cities";
import { createHeadingSlugger } from "@/lib/heading-slug";
import { NICHES, nicheSlug } from "@/lib/niches";
import { buildMetadata } from "@/lib/seo";
import { serviceNode } from "@/lib/structured-data";

/**
 * The dental pricing page: every dental clinic website package on one route,
 * reached from the "View Packages" CTA on the dental solution landing page.
 *
 * A dedicated static segment rather than `/solutions/[slug]/packages`: the
 * nested form would generate a packages route for all ten niches, and only
 * the dental niche has published pricing. A static sibling segment also takes
 * routing precedence over the `[slug]` catch-all, so the ten niche routes are
 * unaffected.
 */

const ROUTE_PATH = "/solutions/dental-clinic-website-packages";

const DENTAL_NICHE = NICHES.find((niche) => niche.id === "dental-medical");
const CITY = findApprovedCity("hyderabad");

/** Heading `id`s, derived through this route's single shared slugger (Requirement 9.5). */
function packagesHeadingIds(
  slugger: (text: string) => string,
): Record<string, string> {
  const ids: Record<string, string> = {};
  for (const heading of DENTAL_PACKAGES_HEADINGS) {
    ids[heading] = slugger(heading);
  }
  return ids;
}

export function generateMetadata(): Metadata {
  return buildMetadata({
    path: ROUTE_PATH,
    title: "Dental Clinic Website Packages & Pricing in Hyderabad",
    description:
      "Transparent dental website pricing in Hyderabad: five packages from ₹10,000 to ₹1,25,000, plus AI chatbot, AI receptionist, and SEO add-ons.",
    type: "website",
    eyebrow: "Dental packages",
  });
}

export default function DentalPackagesPage() {
  if (!DENTAL_NICHE || !CITY) {
    // Only reachable if the dental niche or the Hyderabad city token is
    // removed from the catalog, in which case this route has no content to
    // stand behind and should not be served.
    notFound();
  }

  const solutionPath = `/solutions/${nicheSlug(DENTAL_NICHE, CITY.token)}`;
  const slugger = createHeadingSlugger();

  return (
    <>
      <JsonLd
        nodes={[
          serviceNode(
            {
              id: "dental-medical-packages",
              name: "Dental Clinic Website Packages",
              description:
                "Fixed-scope dental clinic website packages for practices in Hyderabad, from a premium single-page clinic site to a multi-page SEO build with an AI chatbot and AI receptionist.",
              serviceType: "Dental clinic website design and development",
            },
            { areaServed: [CITY.displayName], url: ROUTE_PATH },
          ),
        ]}
      />
      <div className="mx-auto max-w-6xl px-6 pt-6 lg:px-8">
        <Breadcrumb
          trail={[
            { name: "Solutions", path: "/solutions" },
            {
              name: `Dental & Medical in ${CITY.displayName}`,
              path: solutionPath,
            },
            { name: "Packages & Pricing", path: ROUTE_PATH },
          ]}
        />
      </div>
      <DentalPackagesLanding
        cityLabel={CITY.displayName}
        solutionPath={solutionPath}
        headingIds={packagesHeadingIds(slugger)}
      />
    </>
  );
}
